"""Byte-for-byte proof the evidence bar did not move (OD-22 spec D3).

The OD-22 primary-source intake lane adds leads to the EXISTING chain; it
must not relitigate the bar. This gate asserts, on every CI run:

- the decision files the spec bars from editing (src/temporal.py,
  src/evidence.py, src/screening.py, src/lifecycle_rubric.py) are
  hash-identical to the recorded snapshot;
- data/gold_set.json itself is frozen;
- check_origin_dates and screen_saved_source outputs are unchanged over
  deterministic fixtures derived from the gold set — 26 origin-date and
  25 saved-source cases covering the passing, temporal-failure, canary,
  tier-unknown and quote-missing branches, plus one historical-official
  pass;
- golden parse_extraction outputs over a transcript fixture and a budget
  page-range slice are unchanged (the OD-22 lane fixtures, recorded
  model responses, no network).

Expectations live in data/gold_gate_expectations.json, generated by
tests/generate_gold_gate_expectations.py. A change to a frozen file
fails HERE, before anything re-verdicts or softens the gate.
"""

import hashlib
import json
import tempfile
import unittest
from datetime import date
from pathlib import Path

from src.evidence import screen_saved_source
from src.extract import parse_extraction
from src.temporal import check_origin_dates

REPO_ROOT = Path(__file__).resolve().parent.parent
EXPECTATIONS = json.loads(
    (REPO_ROOT / "data" / "gold_gate_expectations.json").read_text(encoding="utf-8")
)


def _date(value):
    return date.fromisoformat(value)


class FrozenDecisionFileTests(unittest.TestCase):
    def test_decision_files_are_hash_identical(self):
        for name, recorded in EXPECTATIONS["frozen_files"].items():
            with self.subTest(file=name):
                current = hashlib.sha256((REPO_ROOT / name).read_bytes()).hexdigest()
                self.assertEqual(current, recorded,
                                 f"{name} changed; the OD-22 spec bars edits to "
                                 "decision logic. If the change was deliberately "
                                 "reviewed, regenerate the expectations and show "
                                 "gold-set outputs unchanged in the diff.")

    def test_gold_set_is_frozen(self):
        current = hashlib.sha256(
            (REPO_ROOT / "data" / "gold_set.json").read_bytes()
        ).hexdigest()
        self.assertEqual(current, EXPECTATIONS["gold_set_sha256"])


class CheckOriginDatesUnchangedTests(unittest.TestCase):
    def test_recorded_outputs_are_reproduced_exactly(self):
        for case in EXPECTATIONS["origin_dates"]:
            with self.subTest(promise=case["promise_id"], scenario=case["scenario"]):
                inputs = case["inputs"]
                output = check_origin_dates(
                    _date(inputs["promised"]) if inputs.get("promised") else None,
                    _date(inputs["published"]) if inputs.get("published") else None,
                    _date(inputs["deadline"]) if inputs.get("deadline") else None,
                    historical_official=inputs.get("historical_official", False),
                    historical_origin_confirmed=inputs.get(
                        "historical_origin_confirmed", False),
                    quote=inputs.get("quote", ""),
                    source_text=inputs.get("source_text", ""),
                )
                self.assertEqual(output, case["output"])


class ScreenSavedSourceUnchangedTests(unittest.TestCase):
    def _archive(self, promise_id, text, digest):
        root = Path(tempfile.mkdtemp())
        directory = root / promise_id
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"{digest}.txt"
        path.write_text(text, encoding="utf-8")
        return root, str(path)

    def test_recorded_outputs_are_reproduced_exactly(self):
        for case in EXPECTATIONS["saved_source"]:
            with self.subTest(gold=case["gold_promise_id"], scenario=case["scenario"]):
                inputs = case["inputs"]
                root, path = self._archive(
                    case["promise_id"], inputs["text"], inputs["digest"]
                )
                output = screen_saved_source(
                    root=root, promise_id=case["promise_id"], path=path,
                    digest=inputs["digest"], quote=inputs["quote"],
                    url=inputs["url"], source_tier=inputs["source_tier"],
                )
                self.assertEqual(output, case["output"])


class GoldenExtractionTests(unittest.TestCase):
    """Golden extraction over a transcript fixture and a budget slice."""

    def _archive(self, promise_id, text, digest):
        root = Path(tempfile.mkdtemp())
        directory = root / promise_id
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"{digest}.txt"
        path.write_text(text, encoding="utf-8")
        return root, str(path)

    def test_transcript_and_budget_slice_extractions_are_unchanged(self):
        for case in EXPECTATIONS["golden_extraction"]:
            with self.subTest(fixture=case["name"]):
                inputs = case["inputs"]
                root, path = self._archive(
                    case["promise_id"], inputs["source_text"], inputs["digest"]
                )
                candidates = parse_extraction(
                    root=root, promise_id=case["promise_id"], path=path,
                    digest=inputs["digest"], response=inputs["response"],
                    published=_date(inputs["published"]),
                )
                self.assertEqual(
                    [c.model_dump(mode="json") for c in candidates], case["expected"]
                )


if __name__ == "__main__":
    unittest.main()
